export function getDistrictsForState(state: string): string[] {
  if (!state) return [];
  return STATE_DISTRICTS[state] || [
    'Central District',
    'North District',
    'South District',
    'East District',
    'West District',
    'Capital District',
    'Other District'
  ];
}

export function getCitiesForDistrict(district: string, state?: string): string[] {
  if (!district) return [];
  if (DISTRICT_CITIES[district]) {
    return DISTRICT_CITIES[district];
  }
  // Generic fallback cities
  const cleanDistrict = district.replace(/\s*\(.*?\)\s*/g, '').trim();
  return [
    `${cleanDistrict} City`,
    `${cleanDistrict} Main Market / Hub`,
    `${cleanDistrict} Industrial Area`,
    'Other City'
  ];
}
