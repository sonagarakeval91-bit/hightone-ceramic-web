/**
 * Recursively strips undefined keys so Firestore accepts clean JSON maps/arrays.
 */
export function stripUndefinedDeep<T>(value: T): T {
  if (Array.isArray(value)) {
    return value.map((item) => stripUndefinedDeep(item)) as unknown as T;
  }
  if (value !== null && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      if (v !== undefined) {
        out[k] = stripUndefinedDeep(v);
      }
    }
    return out as T;
  }
  return value;
}

/**
 * Computes deterministic 64-character lowercase SHA-256 hex digest of dealer credentials.
 */
export async function computeDealerCredHash(userId: string, password: string): Promise<string> {
  const normalized = `${userId.trim().toLowerCase()}::${password.trim()}`;
  const data = new TextEncoder().encode(normalized);
  const hashBuffer = await crypto.subtle.digest('SHA-256', data);
  const hashArray = Array.from(new Uint8Array(hashBuffer));
  return hashArray.map((b) => b.toString(16).padStart(2, '0')).join('');
}

export const computeCredentialHash = computeDealerCredHash;
